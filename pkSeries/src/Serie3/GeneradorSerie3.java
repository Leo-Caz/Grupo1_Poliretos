    private String g1_generarF1(int niveles, TipoBucle tipo) {
        if (niveles <= 0) {
            return "";
        }
        StringBuilder texto = new StringBuilder();
        switch (tipo) {
            case FOR:
                for (int fila = 0; fila < niveles; fila++) {
                    StringBuilder linea = new StringBuilder();
                    for (int columna = 0; columna < niveles; columna++) {
                        char simbolo = g1_obtenerSimboloF1(fila, columna, niveles);
                        linea.append(simbolo);
                        if (columna < niveles - 1) {
                            linea.append(' ');
                        }
                    }
                    g1_agregarLinea(texto, linea.toString());
                }
                break;
            case WHILE:
                int filaWhile = 0;
                while (filaWhile < niveles) {
                    StringBuilder linea = new StringBuilder();
                    int columnaWhile = 0;
                    while (columnaWhile < niveles) {
                        char simbolo = g1_obtenerSimboloF1(filaWhile, columnaWhile, niveles);
                        linea.append(simbolo);
                        if (columnaWhile < niveles - 1) {
                            linea.append(' ');
                        }
                        columnaWhile++;
                    }
                    g1_agregarLinea(texto, linea.toString());
                    filaWhile++;
                }
                break;
            case DO_WHILE:
                int filaDo = 0;
                do {
                    StringBuilder linea = new StringBuilder();
                    int columnaDo = 0;
                    do {
                        char simbolo = g1_obtenerSimboloF1(filaDo, columnaDo, niveles);
                        linea.append(simbolo);
                        if (columnaDo < niveles - 1) {
                            linea.append(' ');
                        }
                        columnaDo++;
                    } while (columnaDo < niveles);
                    g1_agregarLinea(texto, linea.toString());
                    filaDo++;
                } while (filaDo < niveles);
                break;
        }
        return texto.toString();
    }

