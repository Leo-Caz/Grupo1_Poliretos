    private String g1_formatearTriangulo(int[][] valores, boolean centrado) {
        StringBuilder texto = new StringBuilder();
        for (int fila = 0; fila < valores.length; fila++) {
            StringBuilder linea = new StringBuilder();
            if (centrado) {
                int espacios = valores.length - fila - 1;
                for (int espacio = 0; espacio < espacios; espacio++) {
                    linea.append(' ');
                }
            }
            for (int columna = 0; columna < valores[fila].length; columna++) {
                if (columna > 0) {
                    linea.append(' ');
                }
                linea.append(valores[fila][columna]);
            }
            g1_agregarLinea(texto, linea.toString());
        }
        return texto.toString();
    }

    private char g1_obtenerSimboloF1(int fila, int columna, int tamanio) {
        if (fila == 0 || fila == tamanio - 1 || columna == 0 || columna == tamanio - 1) {
            return '*';
        }
        return ' ';
    }

    private char g1_obtenerSimboloF2(int fila, int columna, int tamanio) {
        if (fila == 0 || fila == tamanio - 1 || columna == 0 || columna == tamanio - 1) {
            return (fila + columna) % 2 == 0 ? '*' : '+';
        }
        return ' ';
    }

    private char g1_obtenerSimboloX(int fila, int columna, int tamanio, char simboloPrincipal, char simboloSecundario) {
        int reflejo = tamanio - 1 - fila;
        if (fila == columna && fila == reflejo) {
            return simboloPrincipal;
        }
        if (fila == columna) {
            return simboloPrincipal;
        }
        if (columna == reflejo) {
            return simboloSecundario;
        }
        return ' ';
    }

    private void g1_agregarLinea(StringBuilder texto, String linea) {
        if (texto.length() > 0) {
            texto.append(System.lineSeparator());
        }
        texto.append(linea);
    }
